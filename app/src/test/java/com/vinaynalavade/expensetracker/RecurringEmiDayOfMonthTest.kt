    @Test
    fun testScenario8_NoDuplicateGenerationInSamePeriod() {
        val repo = com.vinaynalavade.expensetracker.data.repository.RecurringTransactionRepositoryImpl(
            FakeRecurringDao(),
            FakeTxDao()
        )
        // Generated on Aug 3
        val entity = createEntity(
            dayOfMonth = 3,
            startDate = LocalDate.of(2026, 8, 1),
            lastGeneratedDate = LocalDate.of(2026, 8, 3)
        )

        // Same day restart
        assertFalse(repo.checkIfDue(entity, LocalDate.of(2026, 8, 3)))
        // Subsequent days in August
        assertFalse(repo.checkIfDue(entity, LocalDate.of(2026, 8, 4)))
        assertFalse(repo.checkIfDue(entity, LocalDate.of(2026, 8, 23)))
        assertFalse(repo.checkIfDue(entity, LocalDate.of(2026, 8, 31)))

        // Next month (Sept 3) -> Due!
        assertTrue(repo.checkIfDue(entity, LocalDate.of(2026, 9, 3)))
    }

