    // ─── Fake Repository ───

    private class FakeRecurringRepository : RecurringTransactionRepository {
        val items = mutableMapOf<Long, RecurringTransaction>()
        private var nextId = 1L

        override fun getRecurringTransactions(): Flow<List<RecurringTransaction>> =
            flowOf(items.values.toList())

        override fun getRecurringTransactionById(id: Long): Flow<RecurringTransaction?> =
            flowOf(items[id])

        override suspend fun insertRecurringTransaction(recurringTransaction: RecurringTransaction): AppResult<Long> {
            val id = nextId++
            items[id] = recurringTransaction.copy(id = id)
            return AppResult.Success(id)
        }

        override suspend fun updateRecurringTransaction(recurringTransaction: RecurringTransaction): AppResult<Unit> {
            items[recurringTransaction.id] = recurringTransaction
            return AppResult.Success(Unit)
        }

        override suspend fun deleteRecurringTransaction(id: Long): AppResult<Unit> {
            items.remove(id)
            return AppResult.Success(Unit)
        }

        override suspend fun processDueOccurrences(): AppResult<Int> {
            return AppResult.Success(0)
        }
    }
